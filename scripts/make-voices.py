#!/usr/bin/env python3
"""Build bundled, synthetic English game calls with FFmpeg/libflite.

No recordings from the reference game are used. Runtime needs only the MP3
and generated voices.js, not Python, FFmpeg, a TTS service or an API key.
"""
from pathlib import Path
import json
import subprocess
import tempfile
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
RATE = 44100
CALLS = {
    'red': 'Red!', 'yellow': 'Yellow!', 'green': 'Green!', 'blue': 'Blue!',
    'reverse': 'Reverse!', 'skip': 'Skip!', 'uno': 'Oo no!',
    'draw-two': 'Draw two!', 'draw-four': 'Draw four!',
    'your-turn': 'Your turn!', 'hurry': 'Hurry up!',
    'thirty-seconds': 'Thirty seconds!', 'ten-seconds': 'Ten seconds!',
    'time-up': 'Time is up!',
}

def main():
    clips = {}
    parts = [np.zeros(round(RATE * .4), dtype=np.float32)]
    position = len(parts[0])
    with tempfile.TemporaryDirectory() as directory:
        for name, words in CALLS.items():
            txt = Path(directory) / 'words.txt'
            txt.write_text(words)
            # A bright, short game call. Silence trim keeps the calls responsive.
            pcm = subprocess.check_output([
                'ffmpeg', '-v', 'error', '-f', 'lavfi', '-i',
                f'flite=textfile={txt}:voice=slt', '-af',
                'silenceremove=start_periods=1:start_threshold=-42dB,'
                'asetrate=17600,aresample=44100,highpass=f=100,lowpass=f=7200,'
                'acompressor=threshold=0.12:ratio=3:attack=5:release=60,alimiter=limit=0.85',
                '-ar', str(RATE), '-ac', '1', '-f', 'f32le', '-'
            ])
            samples = np.frombuffer(pcm, dtype='<f4').copy()
            peak = float(np.max(np.abs(samples))) if len(samples) else 0
            if peak < .01:
                raise RuntimeError(f'Empty call: {name}')
            voiced = np.flatnonzero(np.abs(samples) > .003)
            samples = samples[:min(len(samples), int(voiced[-1]) + round(RATE * .08))]
            samples *= .80 / peak
            clips[name] = {'offset': round(position / RATE, 5), 'duration': round(len(samples) / RATE, 5)}
            parts.extend([samples, np.zeros(round(RATE * .16), dtype=np.float32)])
            position += len(samples) + len(parts[-1])
        out = ROOT / 'public/assets/audio/voice-pack.mp3'
        subprocess.run([
            'ffmpeg', '-y', '-v', 'error', '-f', 'f32le', '-ar', str(RATE),
            '-ac', '1', '-i', '-', '-codec:a', 'libmp3lame', '-b:a', '128k', str(out)
        ], input=np.concatenate(parts).astype('<f4').tobytes(), check=True)
    (ROOT / 'public/voices.js').write_text(
        '// Generated by scripts/make-voices.py; synthetic game calls.\n'
        'export const VOICE_URL = "/assets/audio/voice-pack.mp3?v=1.2";\n'
        'export const VOICE_CLIPS = ' + json.dumps(clips, indent=2) + ';\n'
    )
    print(f'{len(clips)} calls, {position/RATE:.2f}s, {out.stat().st_size} bytes')

if __name__ == '__main__':
    main()
